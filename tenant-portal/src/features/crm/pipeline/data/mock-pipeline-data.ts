export function getMockBoard(): OpportunityBoard {
  const stages: OpportunityBoardLane[] = mockStages.map(stage => {
    const items = mockOpportunities.filter(o => o.stageId === stage.id);
    const amountSum = items.reduce((acc, curr) => acc + curr.amount, 0);
    
    return {
      stage,
      items,
      summary: {
        totalCount: items.length,
        amountsByCurrency: { "SAR": amountSum }
      },
      activitySummary: {
        noOpenCount: items.filter(i => i.activityState === "NO_OPEN").length,
        overdueCount: items.filter(i => i.activityState === "OVERDUE").length,
        todayCount: items.filter(i => i.activityState === "TODAY").length,
        futureCount: items.filter(i => i.activityState === "FUTURE").length,
      },
      pageInfo: {
        limit: 10,
        hasMore: false,
      }
    };
  });

  return {
    pipeline: mockPipeline,
    stages,
  };
}
