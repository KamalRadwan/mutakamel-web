function vizForShape(
  shape: ResultShape,
  rowKind?: 'ALERT' | 'RANKED' | 'SCORECARD',
): Visualization[] {
  if (shape === 'ROWS') {
    if (rowKind === 'ALERT') return ['ALERT_LIST', 'TABLE'];
    if (rowKind === 'RANKED') return ['LEADERBOARD', 'TABLE'];
    if (rowKind === 'SCORECARD') return ['SCORECARD', 'TABLE'];
    return ['TABLE'];
  }
  return VISUALIZATIONS.filter((v) => v.shapes.includes(shape)).map((v) => v.key);
}

