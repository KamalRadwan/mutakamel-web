import type { ReportCatalogueItem, ReportDomain, ReportReadiness } from './catalogue.model';

type ReportSeed = readonly [
  code: string | null,
  reportKey: string,
  domain: ReportDomain,
  titleEn: string,
  titleAr: string,
  summaryEn: string,
  summaryAr: string,
  readiness: ReportReadiness,
  pinnedCount: number,
  favourite?: boolean,
  dashboardId?: string | null,
];

function buildReports(seeds: readonly ReportSeed[]): ReportCatalogueItem[] {
  return seeds.map(
    ([
      code,
      reportKey,
      domain,
      en,
      ar,
      summaryEn,
      summaryAr,
      readiness,
      pinnedCount,
      favourite = false,
      dashboardId = null,
    ]) => ({
      reportKey,
      domain,
      code,
      title: { en, ar },
      summary: { en: summaryEn, ar: summaryAr },
      blueprintRevision: 1,
      readiness,
      favourite,
      dashboardId,
      pinnedCount,
    }),
  );
}

