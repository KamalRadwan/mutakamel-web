"use client";
import { useCallback, useLayoutEffect, useMemo, useRef, useState } from "react";
import { generateUUIDv7 } from "@/lib/uuid";
import { useToast } from "@/design-system";
import { useI18n } from "@/i18n/I18nContext";
import { normalizeApiError } from "@/lib/api/errors";
import { isTradeReplay, tradeIfMatch, tradePost } from "../../../trade-api";
import { inventoryFormMessage, inventoryMessage } from "../../inventory-messages";

// A movement can return all500document lines (Inventory CreateReceiptDto/CreateDeliveryDto).
const MOVEMENT_RESPONSE_LIMIT_BYTES = 2_000_000;

export function useMovementCommandRunner(headers: Record<string, string>, authKey: string) {
  const { t } = useI18n();
  const toast = useToast();
  const owner = useMemo(() => ({ authKey }), [authKey]);
  const [pending, setPending] = useState<{ owner: object; operation: string } | null>(null);
  const [failure, setFailure] = useState<{ owner: object; error: string | null }>({ owner, error: null });
  const [unresolvedOwner, setUnresolvedOwner] = useState<object | null>(null);
  const activeActor = useRef(owner);
  useLayoutEffect(() => { activeActor.current = owner; }, [owner]);
  const setFormError = useCallback((error: string | null) => setFailure({ owner, error }), [owner]);
  const inFlight = useRef(false);
  const unresolved = useRef<{owner: object; path: string; fingerprint: string; body: unknown; headers: Record<string, string>} | null>(null);
  const original = useRef<{ operation: string; onSuccess?: (data: unknown) => void } | null>(null);
  const run = useCallback(
    async (
      operation: string,
      call: () => Promise<{ headers: Headers; data: unknown }>,
      onSuccess?: (data: unknown) => void,
    ): Promise<boolean> => {
      if (inFlight.current) return false;
      inFlight.current = true;
      if (!unresolved.current || unresolved.current.owner !== owner) original.current = { operation, onSuccess };
      setPending({ owner, operation });
      setFormError(null);
      try {
        const response = await call();
        if (activeActor.current !== owner) return false;
        onSuccess?.(response.data);
        unresolved.current = null;
        setUnresolvedOwner(null);
        toast.success(
          t.tradeCommon.savedTitle,
          isTradeReplay(response.headers)
            ? t.tradeCommon.replayedDescription
            : t.tradeInventory.movementAccepted,
        );
        return true;
      } catch (error) {
        if (activeActor.current !== owner) return false;
        if (error instanceof Error && error.message === "INVENTORY_UNRESOLVED_WRITE") {
          setFormError(t.tradeInventory.unresolvedWrite);
          return false;
        }
        const normalized = normalizeApiError(error);
        // A client rejection resolves the write, including an unchanged retry.
        // Keep its identity only while transport/server failures or invalid
        // success payloads leave the outcome unknown.
        if (normalized.status >= 400 && normalized.status < 500 && normalized.code !== "TRADE.IDEMPOTENCY.IN_FLIGHT") {
          unresolved.current = null;
        }
        setUnresolvedOwner(unresolved.current ? owner : null);
        if (normalized.code === "TRADE.IDEMPOTENCY.IN_FLIGHT") {
          setFormError(t.tradeInventory.unresolvedWrite);
          return false;
        }
        if (normalized.code === "TRADE.CONCURRENCY.STALE_VERSION") {
          setFormError(t.tradeInventory.movementStaleHandle);
          return false;
        }
        if (normalized.status === 403) {
          setFormError(t.tradeInventory.movementLookupPermission);
          return false;
        }
        if (toast.outcomeFromApi(normalized)) return false;
        setFormError(inventoryMessage(normalized, t) ?? inventoryFormMessage(error, t));
        return false;
      } finally {
        inFlight.current = false;
        setPending(null);
      }
    },
    [toast, t, owner, setFormError],
  );

  const post = (path: string, body: unknown, ifMatch?: number) => {
    if (unresolved.current?.owner !== owner) unresolved.current = null;
    // Business keys are generated by builders; compare the remaining payload
    // so an unchanged retry can reuse the original body and HTTP identity.
    const fingerprint = JSON.stringify([path, headers, ifMatch, body], (key, value: unknown) =>
      key === "operationKey" || key === "intentKey" ? undefined : value,
    );
    if (unresolved.current && unresolved.current.fingerprint !== fingerprint) {
      throw new Error("INVENTORY_UNRESOLVED_WRITE");
    }
    unresolved.current ??= {
      owner,
      path,
      fingerprint,
      body,
      headers: {
        ...headers,
        ...(ifMatch === undefined ? {} : { "If-Match": tradeIfMatch(ifMatch) }),
        "x-idempotency-key": generateUUIDv7(),
      },
    };
    return tradePost(path as Parameters<typeof tradePost>[0], unresolved.current.body, {
      headers: unresolved.current.headers,
      maxResponseBytes: MOVEMENT_RESPONSE_LIMIT_BYTES,
    });
  };

  return { pending: pending?.owner === owner ? pending.operation : null, formError: failure.owner === owner ? failure.error : null,
    setFormError, hasUnresolvedWrite: unresolvedOwner === owner, run, post,
    retryUnresolved: () => {
      const request = unresolved.current;
      const attempt = original.current;
      if (!request || request.owner !== owner || !attempt) return Promise.resolve(false);
      return run(attempt.operation, () => tradePost(request.path as Parameters<typeof tradePost>[0], request.body,
        { headers: request.headers, maxResponseBytes: MOVEMENT_RESPONSE_LIMIT_BYTES }), attempt.onSuccess);
    },
  };
}
